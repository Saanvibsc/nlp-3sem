def extract_bert_entities(text):

    # Truncate to safe token boundary for BERT
    clean_input = str(text)[:1000]
    results = bert_ner(clean_input)

    entities = []

    for result in results:
        w = str(result.get("word", "")).strip()
        score = float(result.get("score", 1.0))
        label = result.get("entity_group", "MISC")

        # Merge subword tokens (e.g. ##ren, ##dra)
        if w.startswith("##") and entities and entities[-1]["label"] == label:
            entities[-1]["text"] += w[2:]
            entities[-1]["end"] = int(result["end"])
            entities[-1]["score"] = round((entities[-1]["score"] + score) / 2, 4)
        else:
            clean_word = w.lstrip("#").strip()
            if clean_word:
                entities.append({
                    "text": clean_word,
                    "label": label,
                    "score": round(score, 4),
                    "start": int(result["start"]),
                    "end": int(result["end"])
                })

    return entities



def normalize_label(label):

    return label_mapping.get(
        label.upper(),
        label.upper()
    )

def create_entity_set(entities):

    entity_set = set()

    for entity in entities:

        text = (
            entity["text"]
            .strip()
            .lower()
        )

        label = normalize_label(
            entity["label"]
        )

        entity_set.add(
            (text, label)
        )

    return entity_set

"""# **14. Precision, Recall & F1 Evaluation**"""


true_entities_spacy = set()
pred_entities_spacy = set()

for _, row in annotation_df.iterrows():

    # Human ground truth
    manual_entities = (
        parse_manual_entities(
            row["Manual_Entities"]
        )
    )

    # spaCy predictions
    predicted_entities = (
        extract_spacy_entities(
            row["Annotation_Text"]
        )
    )

    true_entities_spacy.update(
        create_entity_set(
            manual_entities
        )
    )

    pred_entities_spacy.update(
        create_entity_set(
            predicted_entities
        )
    )

tp_spacy = len(
    true_entities_spacy &
    pred_entities_spacy
)

fp_spacy = len(
    pred_entities_spacy -
    true_entities_spacy
)

fn_spacy = len(
    true_entities_spacy -
    pred_entities_spacy
)


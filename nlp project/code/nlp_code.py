def parse_manual_entities(entity_string):

    if pd.isna(entity_string):
        return []

    entity_string = str(
        entity_string
    ).strip()

    if entity_string == "":
        return []

    entities = []

    parts = entity_string.split(";")

    for part in parts:

        part = part.strip()

        if "|" not in part:
            continue

        entity_text, entity_label = (
            part.rsplit("|", 1)
        )

        entity_text = entity_text.strip()
        entity_label = entity_label.strip().upper()

        if entity_text and entity_label:

            entities.append({
                "text": entity_text,
                "label": entity_label
            })

    return entities


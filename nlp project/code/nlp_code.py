"""# **13. Human Verification & Ground Truth Creation**
The selected Kaggle news dataset does not contain predefined Named Entity Recognition (NER)
labels. Therefore, there is no ground truth available to directly measure how accurately
spaCy and BERT identify entities.

To create a manageable evaluation dataset, 20 news articles are randomly selected and only
the first 3,000 characters of each article are used. This provides enough text and named
entities for evaluation while keeping the manual verification process practical.

First, spaCy NER is applied to these 20 article samples to automatically generate candidate
entity predictions. Instead of manually identifying every entity from scratch, these
predictions are reviewed by a human. Incorrect entities are corrected, missing entities are
added, and wrongly classified entities are changed to the appropriate category.

The corrected annotations are then treated as the ground truth, which represents the expected
correct entities for the selected text.

Finally, the predictions produced by spaCy and BERT are compared with this ground truth.
This allows us to calculate Precision, Recall, and F1-Score and quantitatively evaluate the
performance of both NER models.
"""

